#!/usr/bin/env python3
"""Re-derive every Phase 6 golden pin from the tracked .sol artifact.

WHY THIS EXISTS (docs/REVIEW.md R-38). The Lean golden gates in
Midfall/Generator/YulGolden.lean compare an AST against a PINNED STRING, not
against the file. Nothing in Lean ever opens the .sol, so the artifact could be
deleted, edited, or regenerated by a different generator and every gate would
stay green. This script is the missing half of the chain:

    bytes on disk --(this script)--> pinned string in YulGolden.lean
    pinned string --(the Lean gate)--> printed AST

For each fixture it reads the cited line range out of the cited .sol, applies the
tokenisation documented in YulGolden.lean, and asserts

    "{" ++ tokens ++ "}" == <base>_committed

plus the line, byte and token counts and the sha256 recorded in the fixture's doc
comment. It is wired into scripts/checks.sh, so CI fails when the artifact moves
and the pins do not - and, symmetrically, when a pin is edited and the artifact
was not the source of the edit.

THE TOKENISATION, exactly as YulGolden.lean documents it:
  * every '//' runs to end of line and is dropped, line by line;
  * whitespace is a token boundary and nothing more (so LF and TAB behave like
    SPACE);
  * each of '(' ')' '{' '}' ',' '-' '>' '=' ':' is its own token, EXCEPT that
    the pair ':=' is kept whole - that is the one place this script and Lean's
    padYulPunct differ, and it is harmless: Lean re-tokenises the pinned string
    on both sides of every comparison, so ':=' splitting into ':' '=' cannot
    change a verdict;
  * a numeric literal is reduced to its value, so '0x20', '0x0020' and '32' are
    one token.

THE HASH RECIPE, corrected. The commit that introduced these pins told the reader
to re-derive them with "sed -n 'A,Bp' FILE | shasum -a 256". That reproduces NONE
of the nine hashes: sed appends a newline after the last selected line, and the
slice as pinned has none. The slice is lines A..B joined by LF with NO trailing
LF, hashed as UTF-8; the byte counts in the doc comments are of that same slice.

THE SECOND JOB (docs/REVIEW.md R-40 F2): the five `fixtureAnchors` in
Midfall/Generator/Templates.lean are hand-typed (partial, artifact line) pairs,
and the Lean gate `includeOrder_matchesFixtureAnchors_ok` claims they are
provenance-checked here. Before R-40 they were not - replacing all five line
numbers with 1,2,3,4,5 reddened nothing. So this script also parses
`fixtureAnchors` and `verifierIncludes` out of Templates.lean and asserts, for
each anchor, that (i) the partial is in the include registry, (ii) the partial
file exists on disk, and (iii) the line number is the START of a real pinned
fixture slice in the dump that the partial expands into. What it still cannot
check, and does not claim to: that the named partial is the file that actually
generated that dump region. The dump is rendered Askama output, so the partial's
source lines do not appear verbatim in it (measured: 2 of 5 anchors have their
slice's first line present in the named partial), and no Lean or Python term
expands the templates. The anchor therefore pins WHERE a fixture starts and THAT
the partial is a real registry entry - not WHICH partial wrote it.

THE THIRD JOB (docs/REVIEW.md R-40 F7): the Lean gate 'includeOrder_matches-
FixtureAnchors_ok' orders only the five partials that own a pinned slice, so the
other eight verifier partials and both evaluator partials could be listed in any
order and nothing noticed. So this script also re-reads the include lines of
contracts/Halo2Verifier.sol and contracts/Halo2QuotientEvaluator.sol and asserts
that 'verifierIncludes' and 'evaluatorIncludes' are those lists, in that order,
and that the line numbers the two doc comments state are the real ones. What it
still cannot check is the same limit as the anchors: nothing here runs Askama, so
the templates are the source of the ORDER, not proof of which partial wrote
which dump region.

WHAT MAKES THIS FAIL, concretely: a regenerated or hand-edited .sol (one byte
inside a cited range changes the hash and usually the token stream); a deleted or
untracked artifact; a pin edited in YulGolden.lean with no matching change to the
artifact; a fixture added without a gate, or a pin with no fixture; and a string
literal appearing inside a cited range, which would break the naive '//'-cut that
both this script and YulGolden.stripLineComment rely on - that case is reported
rather than silently mis-tokenised.
"""

import hashlib
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
FORMAL = HERE.parent
REPO = FORMAL.parent
GOLDEN = FORMAL / "Midfall" / "Generator" / "YulGolden.lean"

EXPECTED_FIXTURES = 9
EXPECTED_ANCHORS = 5
EXPECTED_VERIFIER_INCLUDES = 13
EXPECTED_EVALUATOR_INCLUDES = 2

TEMPLATES = FORMAL / "Midfall" / "Generator" / "Templates.lean"
TEMPLATE_DIR = REPO / "proofs" / "solidity-verifier" / "templates"

# Which rendered contract a partial expands into, by its directory. The dump is
# the only artifact any fixture cites, so this is how an anchor's line number is
# resolved against the right file.
DIR_TO_DUMP = {
    "verifier": "Halo2Verifier.sol",
    "quotient_numerator": "Halo2QuotientEvaluator.sol",
}

# 'def fixtureAnchors : List (String x Nat) := [ ... ]' - the x is U+00D7, matched
# as '.' so the pattern does not depend on the source encoding.
ANCHORS_DEF = re.compile(
    r"^def fixtureAnchors : List \(String . Nat\) :=\n(?P<body>.*?)\]",
    re.M | re.S,
)
ANCHOR_ITEM = re.compile(r'\(\s*"(?P<path>[^"]+)"\s*,\s*(?P<line>\d+)\s*\)')
INCLUDE_ITEM = re.compile(r'"(?P<path>[^"]+)"')


def includes_def_body(src, name):
    # The list body of 'def <name> : List String := [ ... ]', or None.
    m = re.search(r"^def " + name + r" : List String :=\n(?P<body>.*?)\]",
                  src, re.M | re.S)
    return m.group("body") if m else None


# One include line of a contract template, with or without Askama's
# whitespace-trim dash on either side.
TEMPLATE_INCLUDE = re.compile(r'\{%-?\s*include\s+"(?P<path>[^"]+)"\s*-?%\}')

# '... in template order: lines 85, 87, 89, ...' in the doc comment above a
# registry list, so the line numbers that comment states are re-read too.
DOC_INCLUDE_LINES = re.compile(r"lines ([\d,\s]+)\.")

# The provenance line inside each fixture's doc comment.
PROV = re.compile(
    r"(?P<path>[\w./-]+\.sol):(?P<a>\d+)-(?P<b>\d+)"
    r" - (?P<lines>\d+) lines, (?P<bytes>\d+) bytes, (?P<tokens>\d+) tokens,\s*"
    r"sha256 (?P<sha>[0-9a-f]{64})"
)
AST_DEF = re.compile(r"^def (?P<base>\w+)_ast : Block EVM\.Op := yul% \{", re.M)
PIN_DEF = re.compile(
    r'^def (?P<base>\w+)_committed : String :=\n[ \t]*"(?P<pin>(?:[^"\\]|\\.)*)"\n',
    re.M,
)
GATE_DEF = re.compile(r"^def (?P<base>\w+)_golden_ok : Bool :=", re.M)

PUNCT = set("(){}-,>=")
COLON = ":"

# Lean string-literal escapes that can appear inside a pinned token stream.
LEAN_ESCAPES = {
    "\\": "\\",
    '"': '"',
    "n": "\n",
    "t": "\t",
    "r": "\r",
    "0": "\0",
}


def unlean(raw):
    """Turn the inside of a Lean string literal into its value."""
    out = []
    i = 0
    n = len(raw)
    while i < n:
        ch = raw[i]
        if ch != "\\":
            out.append(ch)
            i += 1
            continue
        nxt = raw[i + 1]
        if nxt in LEAN_ESCAPES:
            out.append(LEAN_ESCAPES[nxt])
            i += 2
        elif nxt == "x":
            j = i + 2
            while j < n and raw[j] in "0123456789abcdefABCDEF":
                j += 1
            out.append(chr(int(raw[i + 2:j], 16)))
            i = j
        else:
            raise ValueError("unsupported Lean escape %r" % raw[i:i + 2])
    return "".join(out)


def strip_comments(text):
    """Drop every '//' comment, line by line (see the module docstring)."""
    return "\n".join(line.split("//")[0] for line in text.split("\n"))


def norm_num(tok):
    """Reduce a hex literal to its decimal value; leave anything else alone."""
    if tok[:2] in ("0x", "0X") and len(tok) > 2:
        return str(int(tok[2:], 16))
    return tok


def tokenise(text):
    """The documented Yul token stream, with ':=' kept whole."""
    toks = []
    cur = []
    i = 0
    n = len(text)

    def flush():
        if cur:
            toks.append(norm_num("".join(cur)))
            del cur[:]

    while i < n:
        ch = text[i]
        if ch.isspace():
            flush()
            i += 1
            continue
        if ch in PUNCT or ch == COLON:
            flush()
            if ch == COLON and i + 1 < n and text[i + 1] == "=":
                toks.append(":=")
                i += 2
                continue
            toks.append(ch)
            i += 1
            continue
        cur.append(ch)
        i += 1
    flush()
    return toks


def slice_of(text, a, b):
    """Lines a..b (1-based, inclusive) joined by LF, with NO trailing newline."""
    lines = text.splitlines()
    if b > len(lines):
        raise ValueError("cited range %d-%d runs past the end of a %d-line file"
                         % (a, b, len(lines)))
    return "\n".join(lines[a - 1:b])


def tracked(rel):
    """True/False if git can answer; None if git is unavailable."""
    try:
        proc = subprocess.run(
            ["git", "-C", str(REPO), "ls-files", "--error-unmatch", rel],
            capture_output=True,
            text=True,
        )
    except OSError:
        return None
    if proc.returncode == 0:
        return True
    if proc.returncode == 1:
        return False
    return None


class Report(object):
    def __init__(self):
        self.problems = []

    def bad(self, msg):
        self.problems.append(msg)


def parse_anchors():
    """(anchors, includes) read out of Templates.lean; (None, None) if absent."""
    if not TEMPLATES.is_file():
        return None, None
    src = TEMPLATES.read_text(encoding="utf-8")
    am = ANCHORS_DEF.search(src)
    body = includes_def_body(src, "verifierIncludes")
    if am is None or body is None:
        return None, None
    anchors = [(m.group("path"), int(m.group("line")))
               for m in ANCHOR_ITEM.finditer(am.group("body"))]
    includes = [m.group("path") for m in INCLUDE_ITEM.finditer(body)]
    return anchors, includes


def template_includes(path):
    # [(line number, included path)] for every include line of a contract
    # template, in the order the template text has them.
    out = []
    for i, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        m = TEMPLATE_INCLUDE.search(line)
        if m is not None:
            out.append((i, m.group("path")))
    return out


def doc_above(src, idx):
    # The doc comment that ends immediately before position idx.
    head = src[:idx]
    end = head.rfind("-/")
    start = head.rfind("/--", 0, end) if end != -1 else -1
    return head[start:end] if start != -1 and end != -1 else ""


def check_include_registry(rep):
    # THE R-40 F7 CROSS-CHECK: the full include order of both contracts.
    #
    # 'fixtureAnchors' pins the relative order of only the five partials that
    # own a pinned slice, so swapping two unanchored entries of
    # 'verifierIncludes', or the two of 'evaluatorIncludes', reddened nothing.
    # This closes that: each registry list is compared element by element, in
    # order, against the include lines of the contract template it claims to
    # transcribe, and the line numbers the Lean doc comment states are compared
    # against the same read. What it still cannot check is unchanged: that a
    # partial's own text is what produced the dump region attributed to it.
    if not TEMPLATES.is_file():
        rep.bad("cannot find %s, so the include registry is not checked at all"
                % TEMPLATES)
        return 0
    src = TEMPLATES.read_text(encoding="utf-8")
    pinned = 0
    for name, tmpl, expect in (
            ("verifierIncludes",
             TEMPLATE_DIR / "contracts" / "Halo2Verifier.sol",
             EXPECTED_VERIFIER_INCLUDES),
            ("evaluatorIncludes",
             TEMPLATE_DIR / "contracts" / "Halo2QuotientEvaluator.sol",
             EXPECTED_EVALUATOR_INCLUDES)):
        body = includes_def_body(src, name)
        if body is None:
            rep.bad("could not parse 'def %s' out of %s" % (name, TEMPLATES.name))
            continue
        lean = [m.group("path") for m in INCLUDE_ITEM.finditer(body)]
        if not tmpl.is_file():
            rep.bad("%s: the contract template %s does not exist, so nothing "
                    "checks the order 'def %s' claims" % (name, tmpl, name))
            continue
        real = template_includes(tmpl)
        if len(real) != expect:
            rep.bad("%s: %s has %d include lines but this script expects %d - "
                    "the template moved and this script was not told"
                    % (name, tmpl.name, len(real), expect))
        if lean != [path for _l, path in real]:
            rep.bad("%s: the registry is not the template's include order - %s "
                    "includes %s, the registry lists %s"
                    % (name, tmpl.name, [path for _l, path in real], lean))
            continue
        m = DOC_INCLUDE_LINES.search(doc_above(src, src.index("def " + name)))
        if m is None:
            rep.bad("%s: the doc comment above 'def %s' no longer states its "
                    "include line numbers as 'lines A, B, ...', so that claim is "
                    "back to being unchecked prose" % (name, name))
            continue
        stated = [int(x) for x in re.findall(r"\d+", m.group(1))]
        if stated != [line for line, _p in real]:
            rep.bad("%s: the doc comment states include lines %s but %s has them "
                    "at %s"
                    % (name, stated, tmpl.name, [line for line, _p in real]))
            continue
        pinned += len(real)
        print("  ok  %-18s %d includes: registry order and stated lines agree (%s)"
              % (name, len(real), tmpl.name))
    return pinned


def check_fixture_anchors(rep, slices):
    """The R-40 F2 cross-check: the hand-typed anchors vs the real slice starts.

    `slices` is [(fixture base, cited artifact path, first line, last line)] as
    re-read from the provenance lines of YulGolden.lean, i.e. the same data this
    script just verified against the bytes on disk. An anchor is only as good as
    a fixture slice starting at that line in the dump its partial expands into.
    """
    anchors, includes = parse_anchors()
    if anchors is None:
        rep.bad("could not parse 'def fixtureAnchors' and 'def verifierIncludes' "
                "out of %s, so the anchors the Lean gate cites are not checked at "
                "all" % TEMPLATES)
        return 0
    if len(anchors) != EXPECTED_ANCHORS:
        rep.bad("found %d fixtureAnchors in %s, expected %d - an anchor was added "
                "or dropped without updating this script"
                % (len(anchors), TEMPLATES.name, EXPECTED_ANCHORS))
    if not includes:
        rep.bad("no verifierIncludes entries parsed from %s" % TEMPLATES.name)
        return 0
    seen = set()
    checked = 0
    for path, line in anchors:
        where = "fixtureAnchors entry (%s, %d)" % (path, line)
        if (path, line) in seen:
            rep.bad("%s: duplicated anchor" % where)
        seen.add((path, line))
        if path not in includes:
            rep.bad("%s: the partial is not in verifierIncludes, so the anchor "
                    "names a file the contract does not include" % where)
        if not (TEMPLATE_DIR / path).is_file():
            rep.bad("%s: no such template file under %s" % (where, TEMPLATE_DIR))
        parts = path.split("/")
        dump = DIR_TO_DUMP.get(parts[-2]) if len(parts) >= 2 else None
        if dump is None:
            rep.bad("%s: cannot tell which rendered contract %s expands into"
                    % (where, path))
            continue
        hits = sorted(base for base, rel, a, _b in slices
                      if pathlib.PurePath(rel).name == dump and a == line)
        if not hits:
            rep.bad("%s: no pinned golden fixture slice starts at line %d of %s, "
                    "so this anchor is a hand-typed number that nothing re-reads "
                    "(R-40 F2)" % (where, line, dump))
            continue
        checked += 1
        print("  ok  %-12s anchor %s:%d -> %s"
              % ("|".join(hits), path, line, dump))
    return checked


def check_fixture(rep, base, prov, pin):
    rel = prov["path"]
    path = REPO / rel
    if not path.is_file():
        rep.bad("%s: cited artifact %s does not exist" % (base, rel))
        return
    if tracked(rel) is False:
        rep.bad("%s: %s is present but NOT tracked by git" % (base, rel))
    text = path.read_text(encoding="utf-8")

    a, b = int(prov["a"]), int(prov["b"])
    try:
        s = slice_of(text, a, b)
    except ValueError as e:
        rep.bad("%s: %s" % (base, e))
        return

    if '"' in s:
        rep.bad(
            "%s: the cited range contains a '\"', so the naive '//'-cut that both "
            "this script and YulGolden.stripLineComment rely on is no longer "
            "exact - re-derive this pin with a lexer" % base)
        return

    toks = tokenise(strip_comments(s))
    want = "{ " + " ".join(toks) + " }"
    if want != pin:
        # Point at the first differing token rather than dumping 1.7 kB.
        wl, pl = want.split(" "), pin.split(" ")
        k = 0
        while k < min(len(wl), len(pl)) and wl[k] == pl[k]:
            k += 1
        lo = max(0, k - 6)
        rep.bad(
            "%s: re-derived token stream differs from the pinned string at token "
            "%d (artifact gives %r, pin says %r) near: ...%s..."
            % (base, k,
               wl[k] if k < len(wl) else "<end of stream>",
               pl[k] if k < len(pl) else "<end of stream>",
               " ".join(wl[lo:k + 6])))
        return

    checks = [
        ("line count", b - a + 1, int(prov["lines"])),
        ("byte count", len(s.encode("utf-8")), int(prov["bytes"])),
        ("token count", len(toks), int(prov["tokens"])),
        ("sha256", hashlib.sha256(s.encode("utf-8")).hexdigest(), prov["sha"]),
    ]
    failed = False
    for name, got, want_v in checks:
        if got != want_v:
            rep.bad("%s: %s mismatch - artifact gives %s, doc comment pins %s"
                    % (base, name, got, want_v))
            failed = True
    if not failed:
        print("  ok  %-12s %s:%d-%d  %d lines, %d bytes, %d tokens"
              % (base, rel, a, b, b - a + 1, len(s.encode("utf-8")), len(toks)))


def main():
    if not GOLDEN.is_file():
        print("check_golden_provenance: cannot find %s" % GOLDEN, file=sys.stderr)
        return 2
    src = GOLDEN.read_text(encoding="utf-8")

    asts = list(AST_DEF.finditer(src))
    pins = dict((m.group("base"), unlean(m.group("pin")))
                for m in PIN_DEF.finditer(src))
    gates = set(m.group("base") for m in GATE_DEF.finditer(src))

    if len(asts) != EXPECTED_FIXTURES:
        print("check_golden_provenance: found %d '<base>_ast' fixtures in %s, "
              "expected %d - a fixture was added or removed without updating this "
              "script" % (len(asts), GOLDEN.name, EXPECTED_FIXTURES),
              file=sys.stderr)
        return 1
    if len(pins) != len(asts):
        print("check_golden_provenance: %d pinned strings for %d ASTs"
              % (len(pins), len(asts)), file=sys.stderr)
        return 1

    rep = Report()
    slices = []
    for m in asts:
        base = m.group("base")
        # The provenance lives in the doc comment that ends immediately before
        # the 'def <base>_ast' line.
        head = src[:m.start()]
        end = head.rfind("-/")
        start = head.rfind("/--", 0, end) if end != -1 else -1
        doc = head[start:end] if start != -1 and end != -1 else ""
        pm = PROV.search(doc)
        if pm is None:
            rep.bad("%s: no provenance line (file:lines - counts, sha256) in the "
                    "doc comment above 'def %s_ast'" % (base, base))
            continue
        if base not in pins:
            rep.bad("%s: no 'def %s_committed' pinned string" % (base, base))
            continue
        if base not in gates:
            rep.bad("%s: no 'def %s_golden_ok' gate, so the pin is dead weight"
                    % (base, base))
            continue
        check_fixture(rep, base, pm.groupdict(), pins[base])
        slices.append((base, pm.group("path"), int(pm.group("a")),
                       int(pm.group("b"))))

    anchor_count = check_fixture_anchors(rep, slices)
    include_count = check_include_registry(rep)

    bases = set(m.group("base") for m in asts)
    for orphan in sorted(set(pins) - bases):
        rep.bad("%s: pinned string with no matching '<base>_ast'" % orphan)
    for orphan in sorted(bases - set(pins)):
        rep.bad("%s: AST with no matching '<base>_committed' pin" % orphan)

    if rep.problems:
        print("GOLDEN PROVENANCE FAILED (%d problem(s)):" % len(rep.problems),
              file=sys.stderr)
        for p in rep.problems:
            print("  " + p, file=sys.stderr)
        return 1

    print("ok: %d golden pins re-derived from the tracked .sol artifacts, %d "
          "fixtureAnchors matched to real slice starts, and %d include orders "
          "pinned against the contract templates"
          % (len(asts), anchor_count, include_count))
    return 0


if __name__ == "__main__":
    sys.exit(main())
