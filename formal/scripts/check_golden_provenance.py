#!/usr/bin/env python3
"""Re-derive every Phase 6 golden pin from the tracked .sol artifact.

WHY THIS EXISTS (docs/REVIEW.md R-38). The Lean golden gates in
Midfall/Generator/YulGolden.lean compare an AST against a PINNED STRING, not
against the file. Nothing in Lean ever opens the .sol, so the artifact could be
deleted, edited, or regenerated by a different generator and every gate would
stay green. This script is the missing half of the chain:

    bytes on disk --(this script)--> pinned string in YulGolden.lean
    pinned string --(the Lean gate)--> printed AST

For each fixture it reads the cited line range out of the cited .sol, applies the
tokenisation documented in YulGolden.lean, and asserts

    "{" ++ tokens ++ "}" == <base>_committed

plus the line, byte and token counts and the sha256 recorded in the fixture's doc
comment. It is wired into scripts/checks.sh, so CI fails when the artifact moves
and the pins do not - and, symmetrically, when a pin is edited and the artifact
was not the source of the edit.

THE TOKENISATION, exactly as YulGolden.lean documents it:
  * every '//' runs to end of line and is dropped, line by line;
  * whitespace is a token boundary and nothing more (so LF and TAB behave like
    SPACE);
  * each of '(' ')' '{' '}' ',' '-' '>' '=' ':' is its own token, EXCEPT that
    the pair ':=' is kept whole - that is the one place this script and Lean's
    padYulPunct differ, and it is harmless: Lean re-tokenises the pinned string
    on both sides of every comparison, so ':=' splitting into ':' '=' cannot
    change a verdict;
  * a numeric literal is reduced to its value, so '0x20', '0x0020' and '32' are
    one token.

THE HASH RECIPE, corrected. The commit that introduced these pins told the reader
to re-derive them with "sed -n 'A,Bp' FILE | shasum -a 256". That reproduces NONE
of the eight hashes: sed appends a newline after the last selected line, and the
slice as pinned has none. The slice is lines A..B joined by LF with NO trailing
LF, hashed as UTF-8; the byte counts in the doc comments are of that same slice.

WHAT MAKES THIS FAIL, concretely: a regenerated or hand-edited .sol (one byte
inside a cited range changes the hash and usually the token stream); a deleted or
untracked artifact; a pin edited in YulGolden.lean with no matching change to the
artifact; a fixture added without a gate, or a pin with no fixture; and a string
literal appearing inside a cited range, which would break the naive '//'-cut that
both this script and YulGolden.stripLineComment rely on - that case is reported
rather than silently mis-tokenised.
"""

import hashlib
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
FORMAL = HERE.parent
REPO = FORMAL.parent
GOLDEN = FORMAL / "Midfall" / "Generator" / "YulGolden.lean"

EXPECTED_FIXTURES = 8

# The provenance line inside each fixture's doc comment.
PROV = re.compile(
    r"(?P<path>[\w./-]+\.sol):(?P<a>\d+)-(?P<b>\d+)"
    r" - (?P<lines>\d+) lines, (?P<bytes>\d+) bytes, (?P<tokens>\d+) tokens,\s*"
    r"sha256 (?P<sha>[0-9a-f]{64})"
)
AST_DEF = re.compile(r"^def (?P<base>\w+)_ast : Block EVM\.Op := yul% \{", re.M)
PIN_DEF = re.compile(
    r'^def (?P<base>\w+)_committed : String :=\n[ \t]*"(?P<pin>(?:[^"\\]|\\.)*)"\n',
    re.M,
)
GATE_DEF = re.compile(r"^def (?P<base>\w+)_golden_ok : Bool :=", re.M)

PUNCT = set("(){}-,>=")
COLON = ":"

# Lean string-literal escapes that can appear inside a pinned token stream.
LEAN_ESCAPES = {
    "\\": "\\",
    '"': '"',
    "n": "\n",
    "t": "\t",
    "r": "\r",
    "0": "\0",
}


def unlean(raw):
    """Turn the inside of a Lean string literal into its value."""
    out = []
    i = 0
    n = len(raw)
    while i < n:
        ch = raw[i]
        if ch != "\\":
            out.append(ch)
            i += 1
            continue
        nxt = raw[i + 1]
        if nxt in LEAN_ESCAPES:
            out.append(LEAN_ESCAPES[nxt])
            i += 2
        elif nxt == "x":
            j = i + 2
            while j < n and raw[j] in "0123456789abcdefABCDEF":
                j += 1
            out.append(chr(int(raw[i + 2:j], 16)))
            i = j
        else:
            raise ValueError("unsupported Lean escape %r" % raw[i:i + 2])
    return "".join(out)


def strip_comments(text):
    """Drop every '//' comment, line by line (see the module docstring)."""
    return "\n".join(line.split("//")[0] for line in text.split("\n"))


def norm_num(tok):
    """Reduce a hex literal to its decimal value; leave anything else alone."""
    if tok[:2] in ("0x", "0X") and len(tok) > 2:
        return str(int(tok[2:], 16))
    return tok


def tokenise(text):
    """The documented Yul token stream, with ':=' kept whole."""
    toks = []
    cur = []
    i = 0
    n = len(text)

    def flush():
        if cur:
            toks.append(norm_num("".join(cur)))
            del cur[:]

    while i < n:
        ch = text[i]
        if ch.isspace():
            flush()
            i += 1
            continue
        if ch in PUNCT or ch == COLON:
            flush()
            if ch == COLON and i + 1 < n and text[i + 1] == "=":
                toks.append(":=")
                i += 2
                continue
            toks.append(ch)
            i += 1
            continue
        cur.append(ch)
        i += 1
    flush()
    return toks


def slice_of(text, a, b):
    """Lines a..b (1-based, inclusive) joined by LF, with NO trailing newline."""
    lines = text.splitlines()
    if b > len(lines):
        raise ValueError("cited range %d-%d runs past the end of a %d-line file"
                         % (a, b, len(lines)))
    return "\n".join(lines[a - 1:b])


def tracked(rel):
    """True/False if git can answer; None if git is unavailable."""
    try:
        proc = subprocess.run(
            ["git", "-C", str(REPO), "ls-files", "--error-unmatch", rel],
            capture_output=True,
            text=True,
        )
    except OSError:
        return None
    if proc.returncode == 0:
        return True
    if proc.returncode == 1:
        return False
    return None


class Report(object):
    def __init__(self):
        self.problems = []

    def bad(self, msg):
        self.problems.append(msg)


def check_fixture(rep, base, prov, pin):
    rel = prov["path"]
    path = REPO / rel
    if not path.is_file():
        rep.bad("%s: cited artifact %s does not exist" % (base, rel))
        return
    if tracked(rel) is False:
        rep.bad("%s: %s is present but NOT tracked by git" % (base, rel))
    text = path.read_text(encoding="utf-8")

    a, b = int(prov["a"]), int(prov["b"])
    try:
        s = slice_of(text, a, b)
    except ValueError as e:
        rep.bad("%s: %s" % (base, e))
        return

    if '"' in s:
        rep.bad(
            "%s: the cited range contains a '\"', so the naive '//'-cut that both "
            "this script and YulGolden.stripLineComment rely on is no longer "
            "exact - re-derive this pin with a lexer" % base)
        return

    toks = tokenise(strip_comments(s))
    want = "{ " + " ".join(toks) + " }"
    if want != pin:
        # Point at the first differing token rather than dumping 1.7 kB.
        wl, pl = want.split(" "), pin.split(" ")
        k = 0
        while k < min(len(wl), len(pl)) and wl[k] == pl[k]:
            k += 1
        lo = max(0, k - 6)
        rep.bad(
            "%s: re-derived token stream differs from the pinned string at token "
            "%d (artifact gives %r, pin says %r) near: ...%s..."
            % (base, k,
               wl[k] if k < len(wl) else "<end of stream>",
               pl[k] if k < len(pl) else "<end of stream>",
               " ".join(wl[lo:k + 6])))
        return

    checks = [
        ("line count", b - a + 1, int(prov["lines"])),
        ("byte count", len(s.encode("utf-8")), int(prov["bytes"])),
        ("token count", len(toks), int(prov["tokens"])),
        ("sha256", hashlib.sha256(s.encode("utf-8")).hexdigest(), prov["sha"]),
    ]
    failed = False
    for name, got, want_v in checks:
        if got != want_v:
            rep.bad("%s: %s mismatch - artifact gives %s, doc comment pins %s"
                    % (base, name, got, want_v))
            failed = True
    if not failed:
        print("  ok  %-12s %s:%d-%d  %d lines, %d bytes, %d tokens"
              % (base, rel, a, b, b - a + 1, len(s.encode("utf-8")), len(toks)))


def main():
    if not GOLDEN.is_file():
        print("check_golden_provenance: cannot find %s" % GOLDEN, file=sys.stderr)
        return 2
    src = GOLDEN.read_text(encoding="utf-8")

    asts = list(AST_DEF.finditer(src))
    pins = dict((m.group("base"), unlean(m.group("pin")))
                for m in PIN_DEF.finditer(src))
    gates = set(m.group("base") for m in GATE_DEF.finditer(src))

    if len(asts) != EXPECTED_FIXTURES:
        print("check_golden_provenance: found %d '<base>_ast' fixtures in %s, "
              "expected %d - a fixture was added or removed without updating this "
              "script" % (len(asts), GOLDEN.name, EXPECTED_FIXTURES),
              file=sys.stderr)
        return 1
    if len(pins) != len(asts):
        print("check_golden_provenance: %d pinned strings for %d ASTs"
              % (len(pins), len(asts)), file=sys.stderr)
        return 1

    rep = Report()
    for m in asts:
        base = m.group("base")
        # The provenance lives in the doc comment that ends immediately before
        # the 'def <base>_ast' line.
        head = src[:m.start()]
        end = head.rfind("-/")
        start = head.rfind("/--", 0, end) if end != -1 else -1
        doc = head[start:end] if start != -1 and end != -1 else ""
        pm = PROV.search(doc)
        if pm is None:
            rep.bad("%s: no provenance line (file:lines - counts, sha256) in the "
                    "doc comment above 'def %s_ast'" % (base, base))
            continue
        if base not in pins:
            rep.bad("%s: no 'def %s_committed' pinned string" % (base, base))
            continue
        if base not in gates:
            rep.bad("%s: no 'def %s_golden_ok' gate, so the pin is dead weight"
                    % (base, base))
            continue
        check_fixture(rep, base, pm.groupdict(), pins[base])

    bases = set(m.group("base") for m in asts)
    for orphan in sorted(set(pins) - bases):
        rep.bad("%s: pinned string with no matching '<base>_ast'" % orphan)
    for orphan in sorted(bases - set(pins)):
        rep.bad("%s: AST with no matching '<base>_committed' pin" % orphan)

    if rep.problems:
        print("GOLDEN PROVENANCE FAILED (%d problem(s)):" % len(rep.problems),
              file=sys.stderr)
        for p in rep.problems:
            print("  " + p, file=sys.stderr)
        return 1

    print("ok: %d golden pins re-derived from the tracked .sol artifacts"
          % len(asts))
    return 0


if __name__ == "__main__":
    sys.exit(main())
