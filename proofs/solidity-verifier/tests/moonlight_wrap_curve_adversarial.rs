fn deployment_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("deployments/sepolia/moonlight-wrap")
}

fn fixture_calldata() -> Vec<u8> {
    let path =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("fixtures/moonlight-wrap/calldata.bin");
    std::fs::read(&path).unwrap_or_else(|e| panic!("missing {}: {e}", path.display()))
}

/// Which layer rejected the input, inferred from gas. The three regimes are
/// far enough apart to be unambiguous: the envelope guards run before any
/// precompile, the full algebraic path costs about as much as an accepted
/// proof, and a precompile that rejects its input consumes everything it was
/// forwarded.
#[derive(Debug, PartialEq, Eq, Clone, Copy)]
enum Stage {
    /// Rejected by an ABI, canonicality, packing or decode guard.
    Guard,
    /// Decoded and absorbed fine; the algebra or the final pairing said no.
    Algebra,
    /// An EIP-2537 precompile rejected the point and burned the gas budget.
    Precompile,
}

fn classify(gas_used: u64, accepted_gas: u64) -> Stage {
    if gas_used > accepted_gas.saturating_mul(4) {
        Stage::Precompile
    } else if gas_used * 2 < accepted_gas {
        Stage::Guard
    } else {
        Stage::Algebra
    }
}

fn expect_reject(evm: &mut Evm, addr: Address, cd: Vec<u8>, accepted: u64, case: &str) -> Stage {
    match evm.try_call_with_gas(addr, cd, GAS_CAP) {
        CallOutcome::Success {
            output, gas_used, ..
        } => panic!(
            "{case}: ACCEPTED (gas {gas_used}, output 0x{}) -- this input must not verify",
            hex::encode(output)
        ),
        CallOutcome::Halt { reason, gas_used } => {
            panic!("{case}: halted ({reason}) after {gas_used} gas; expected a revert")
        }
        CallOutcome::Revert { gas_used, .. } => classify(gas_used, accepted),
    }
}

fn write_acc_point(cd: &mut [u8], point_index: usize, x: &Big, y: &Big) {
    let (xw0, xw1) = encode_coord(x);
    let (yw0, yw1) = encode_coord(y);
    assert_eq!(
        (decode_coord(&xw0, &xw1), decode_coord(&yw0, &yw1)),
        (x.clone(), y.clone()),
        "codec round-trip failed; the test vector would not mean what it claims"
    );
    let base = INSTANCE_START + (ACC_OFFSET + point_index * 4) * 32;
    for (i, w) in [xw0, xw1, yw0, yw1].iter().enumerate() {
        cd[base + i * 32..base + (i + 1) * 32].copy_from_slice(&word_bytes(w));
    }
}

fn acc_word_offset(point_index: usize, word: usize) -> usize {
    INSTANCE_START + (ACC_OFFSET + point_index * 4 + word) * 32
}

