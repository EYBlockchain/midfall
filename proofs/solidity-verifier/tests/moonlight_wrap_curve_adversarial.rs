#[test]
fn deployed_wrap_verifier_rejects_curve_level_attacks() {
    let dir = deployment_dir();
    let vk_src = std::fs::read_to_string(dir.join("Halo2VerifyingKey.sol")).unwrap();
    let ver_src = std::fs::read_to_string(dir.join("Halo2Verifier.sol")).unwrap();
    let calldata = fixture_calldata();

    assert_eq!(
        calldata.len(),
        INSTANCE_START + 19 * 32,
        "fixture calldata does not match the deployed verifier's pinned envelope"
    );
    assert_eq!(
        PROOF_START + PROOF_LEN,
        0x1ec4,
        "proof layout constants disagree"
    );

    // --- vectors, each self-checked so a broken generator cannot silently
    // --- turn an assertion into a tautology -------------------------------
    let (nsx, nsy) = non_subgroup_point();
    assert!(
        on_curve(&nsx, &nsy),
        "non-subgroup vector must be on the curve"
    );
    assert!(
        !in_subgroup(&Pt::Aff(nsx.clone(), nsy.clone())),
        "non-subgroup vector must be outside G1, or it tests nothing"
    );

    let (h_x, h_y) = (Big::from(0u32), Big::from(2u32));
    assert!(on_curve(&h_x, &h_y), "(0,2) must be on the curve");
    assert!(
        !in_subgroup(&Pt::Aff(h_x.clone(), h_y.clone())),
        "(0,2) must be h-torsion"
    );

    let (gx, gy) = generator();
    assert!(
        in_subgroup(&Pt::Aff(gx.clone(), gy.clone())),
        "generator vector must be a valid G1 element, or the pairing test is vacuous"
    );

    // The fixture's own accumulator, recovered and re-encoded. This proves the
    // codec implemented here matches the one the circuit used.
    let read_word = |off: usize| Big::from_bytes_be(&calldata[off..off + 32]);
    let lhs_x = decode_coord(
        &read_word(acc_word_offset(0, 0)),
        &read_word(acc_word_offset(0, 1)),
    );
    let lhs_y = decode_coord(
        &read_word(acc_word_offset(0, 2)),
        &read_word(acc_word_offset(0, 3)),
    );
    assert!(
        on_curve(&lhs_x, &lhs_y) && in_subgroup(&Pt::Aff(lhs_x.clone(), lhs_y.clone())),
        "the fixture's own accumulator must decode to a valid G1 point; \
         if it does not, this file's codec is wrong and every vector below is meaningless"
    );
    let neg_lhs_y = f_sub(&p(), &lhs_y);

    // --- deploy the on-chain sources -------------------------------------
    let mut evm = Evm::default();
    let vk = evm.create(compile_solidity_with_runs(&vk_src, SOLC_OPTIMIZE_RUNS));
    assert_eq!(evm.code_size(vk), 17_025, "VK runtime size drifted");
    let verifier =
        evm.create_with_address_arg(compile_solidity_with_runs(&ver_src, SOLC_OPTIMIZE_RUNS), vk);
    assert_eq!(
        evm.code_size(verifier),
        21_161,
        "verifier runtime size drifted"
    );

    let accepted_gas = match evm.try_call_with_gas(verifier, calldata.clone(), GAS_CAP) {
        CallOutcome::Success {
            output, gas_used, ..
        } => {
            assert_eq!(
                output,
                [vec![0u8; 31], vec![1]].concat(),
                "an accepted proof must return exactly true"
            );
            gas_used
        }
        other => panic!(
            "the deployed contracts must accept the fixture proof, otherwise every \
             rejection below could be a rejection of everything: {other:?}"
        ),
    };

    let mut log: Vec<(String, Stage)> = Vec::new();
    let mut check = |evm: &mut Evm, cd: Vec<u8>, case: &str, want: Stage| {
        let got = expect_reject(evm, verifier, cd, accepted_gas, case);
        assert_eq!(got, want, "{case}: rejected at {got:?}, expected {want:?}");
        log.push((case.to_string(), got));
    };

    // =====================================================================
    // 1. Subgroup membership -- the check the verifier delegates entirely to
    //    EIP-2537 and that nothing else in the suite exercises.
    // =====================================================================
    for point in 0..2usize {
        let mut cd = calldata.clone();
        write_acc_point(&mut cd, point, &nsx, &nsy);
        check(
            &mut evm,
            cd,
            &format!("accumulator point {point} on the curve but outside the r-order subgroup"),
            Stage::Precompile,
        );
    }

    // Same attack on the proof side: every absorbed commitment is claimed to
    // reach a G1MSM. Substituting a non-subgroup point tests that claim for
    // the first commitment of each category in the deployed proof layout.
    let categories: [(&str, usize); 7] = [
        ("advice[0]", 0x0000),
        ("lookup_multiplicity[0]", 0x0780),
        ("permutation_z[0]", 0x0880),
        ("lookup_helper[0]", 0x0b80),
        ("trashcan[0]", 0x0d80),
        ("quotient_limb[0]", 0x0e00),
        ("f_com", 0x1cc0),
    ];
    let ns_padded = padded_g1(&nsx, &nsy);
    for (name, off) in categories {
        let mut cd = calldata.clone();
        cd[PROOF_START + off..PROOF_START + off + 128].copy_from_slice(&ns_padded);
        check(
            &mut evm,
            cd,
            &format!("{name} replaced with a non-subgroup curve point"),
            Stage::Precompile,
        );
    }

    // =====================================================================
    // 2. (0, 2) -- the only curve point with x = 0, which is exactly the
    //    value the codec's `p - 1` sentinel decodes to. h-torsion, so a
    //    correct verifier must reject it; and because x = 0 it is the one
    //    input where the zero sentinel and a real coordinate collide.
    // =====================================================================
    for point in 0..2usize {
        let mut cd = calldata.clone();
        write_acc_point(&mut cd, point, &h_x, &h_y);
        check(
            &mut evm,
            cd,
            &format!("accumulator point {point} set to the h-torsion point (0, 2)"),
            Stage::Guard,
        );
    }

    // =====================================================================
    // 3. Valid G1 elements, wrong values. These clear every encoding, curve
    //    and subgroup check, so only the pairing can reject them. If any of
    //    these were accepted, the accumulator would not be bound at all.
    // =====================================================================
    for point in 0..2usize {
        let mut cd = calldata.clone();
        write_acc_point(&mut cd, point, &gx, &gy);
        check(
            &mut evm,
            cd,
            &format!("accumulator point {point} replaced with the G1 generator"),
            Stage::Algebra,
        );
    }
    {
        let mut cd = calldata.clone();
        write_acc_point(&mut cd, 0, &lhs_x, &neg_lhs_y);
        check(
            &mut evm,
            cd,
            "accumulator lhs negated (still a valid G1 element)",
            Stage::Algebra,
        );
    }
    {
        // Both halves set to the same valid point: individually well-formed,
        // jointly degenerate.
        let mut cd = calldata.clone();
        write_acc_point(&mut cd, 1, &lhs_x, &lhs_y);
        check(
            &mut evm,
            cd,
            "accumulator lhs and rhs set to the same valid point",
            Stage::Algebra,
        );
    }

    // =====================================================================
    // 4. Coordinate encodings that decode outside the base field.
    // =====================================================================
    for point in 0..2usize {
        for (word, label) in [(0usize, "x"), (2, "y")] {
            let mut cd = calldata.clone();
            // Encoded value `p` decodes to `p + 1`, which is not a field
            // element and is not the `p - 1` zero sentinel either.
            let e = p();
            let mask = (Big::from(1u32) << LIMB_BITS) - Big::from(1u32);
            let mut w0 = Big::from(0u32);
            for i in 0..LIMBS_PER_WORD {
                w0 |= ((&e >> (LIMB_BITS * i as u32)) & &mask) << (LIMB_BITS * i as u32);
            }
            let mut w1 = Big::from(0u32);
            for i in LIMBS_PER_WORD..NUM_LIMBS {
                w1 |= ((&e >> (LIMB_BITS * i as u32)) & &mask)
                    << (LIMB_BITS * (i - LIMBS_PER_WORD) as u32);
            }
            assert!(
                decode_coord(&w0, &w1) >= p(),
                "vector must decode out of field"
            );
            let base = acc_word_offset(point, word);
            cd[base..base + 32].copy_from_slice(&word_bytes(&w0));
            cd[base + 32..base + 64].copy_from_slice(&word_bytes(&w1));
            check(
                &mut evm,
                cd,
                &format!("accumulator point {point} {label} decodes to a value >= p"),
                Stage::Guard,
            );
        }
    }

    // =====================================================================
    // 5. Over-packing the SECOND coordinate word. It carries three limbs, so
    //    bits 168..255 are unused; the existing suite only over-packs the
    //    first word's 224-bit boundary.
    // =====================================================================
    for point in 0..2usize {
        for (word, label) in [(1usize, "x"), (3, "y")] {
            let mut cd = calldata.clone();
            let off = acc_word_offset(point, word);
            let mut w = Big::from_bytes_be(&cd[off..off + 32]);
            w |= Big::from(1u32) << (LIMB_BITS * (NUM_LIMBS - LIMBS_PER_WORD) as u32);
            cd[off..off + 32].copy_from_slice(&word_bytes(&w));
            check(
                &mut evm,
                cd,
                &format!("accumulator point {point} {label} second word over-packed past bit 168"),
                Stage::Guard,
            );
        }
    }

    // =====================================================================
    // 6. Identity flag on `y`. Only `x` may carry it (`load_acc_coord` is
    //    called with `allow_id = 0` for `y`), so adding one radix base to
    //    the y word must not produce an accepted infinity.
    // =====================================================================
    for point in 0..2usize {
        let mut cd = calldata.clone();
        let off = acc_word_offset(point, 2);
        let w = Big::from_bytes_be(&cd[off..off + 32]) + (Big::from(1u32) << LIMB_BITS);
        cd[off..off + 32].copy_from_slice(&word_bytes(&w));
        check(
            &mut evm,
            cd,
            &format!("accumulator point {point} carries an identity flag on y"),
            Stage::Precompile,
        );
    }

    // =====================================================================
    // 7. Off-curve accumulator points that are otherwise perfectly encoded.
    // =====================================================================
    for point in 0..2usize {
        let mut cd = calldata.clone();
        // x from a real point, y from a different real point: canonical
        // field elements, correct packing, not on the curve.
        write_acc_point(&mut cd, point, &lhs_x, &gy);
        check(
            &mut evm,
            cd,
            &format!(
                "accumulator point {point} has canonical coordinates that are not on the curve"
            ),
            Stage::Precompile,
        );
    }

    // --- report -----------------------------------------------------------
    println!("\naccepted baseline: {accepted_gas} gas\n");
    println!("{:<74}  rejected by", "case");
    for (case, stage) in &log {
        println!("{case:<74}  {stage:?}");
    }
    println!("\n{} adversarial inputs, all rejected", log.len());
}

/// The two public-input encodings of the accumulator point at infinity that
/// the deployed bytecode currently accepts at the decode layer.
///
/// This is a characterisation test, not an approval. Case B is the
/// always-false `and` guard in `load_acc_coord_shifted`: because the identity
/// flag is never subtracted, the probe fires on the *unflagged* `p - 1`
/// encoding and sets `is_id`, where correct code would fall through to
/// `ok := and(ok, iszero(decoded_zero))` and reject. Both reach the pairing
/// and both are rejected there for this proof, because the accumulator words
/// are transcript-absorbed. Fixed in current codegen; this pins the deployed
/// behaviour so a redeploy shows up as a diff here.
#[test]
fn deployed_wrap_verifier_accepts_two_infinity_encodings_at_the_decode_layer() {
    let dir = deployment_dir();
    let vk_src = std::fs::read_to_string(dir.join("Halo2VerifyingKey.sol")).unwrap();
    let ver_src = std::fs::read_to_string(dir.join("Halo2Verifier.sol")).unwrap();
    let calldata = fixture_calldata();

    let mut evm = Evm::default();
    let vk = evm.create(compile_solidity_with_runs(&vk_src, SOLC_OPTIMIZE_RUNS));
    let verifier =
        evm.create_with_address_arg(compile_solidity_with_runs(&ver_src, SOLC_OPTIMIZE_RUNS), vk);

    let accepted_gas = match evm.try_call_with_gas(verifier, calldata.clone(), GAS_CAP) {
        CallOutcome::Success { gas_used, .. } => gas_used,
        other => panic!("baseline proof must verify: {other:?}"),
    };

    // `p - 1` packed as seven radix-2^56 limbs: the codec's encoding of zero.
    let (sentinel_w0, sentinel_w1) = {
        let e = p() - Big::from(1u32);
        let mask = (Big::from(1u32) << LIMB_BITS) - Big::from(1u32);
        let mut w0 = Big::from(0u32);
        for i in 0..LIMBS_PER_WORD {
            w0 |= ((&e >> (LIMB_BITS * i as u32)) & &mask) << (LIMB_BITS * i as u32);
        }
        let mut w1 = Big::from(0u32);
        for i in LIMBS_PER_WORD..NUM_LIMBS {
            w1 |= ((&e >> (LIMB_BITS * i as u32)) & &mask)
                << (LIMB_BITS * (i - LIMBS_PER_WORD) as u32);
        }
        (w0, w1)
    };
    let flagged_w0 = &sentinel_w0 + (Big::from(1u32) << LIMB_BITS);

    let build = |x_word0: &Big| {
        let mut cd = calldata.clone();
        for point in 0..2usize {
            for (word, value) in [
                (0usize, x_word0.clone()),
                (1, sentinel_w1.clone()),
                (2, sentinel_w0.clone()),
                (3, sentinel_w1.clone()),
            ] {
                let off = acc_word_offset(point, word);
                cd[off..off + 32].copy_from_slice(&word_bytes(&value));
            }
        }
        cd
    };

    for (label, x_word0) in [
        (
            "A: canonical infinity (x = p-1 WITH the identity flag)",
            &flagged_w0,
        ),
        (
            "B: alternate infinity (x = p-1, NO identity flag)",
            &sentinel_w0,
        ),
    ] {
        match evm.try_call_with_gas(verifier, build(x_word0), GAS_CAP) {
            CallOutcome::Revert { gas_used, .. } => {
                let stage = classify(gas_used, accepted_gas);
                assert_eq!(
                    stage,
                    Stage::Algebra,
                    "{label}: expected the decoder to accept this and the pairing to reject it, \
                     but it was rejected at {stage:?} ({gas_used} gas)"
                );
                println!("{label}\n    decode accepted, pairing rejected, {gas_used} gas");
            }
            other => panic!("{label}: expected a revert at the pairing, got {other:?}"),
        }
    }
    println!(
        "\nBoth encodings clear the decoder. Correct behaviour would accept only A; \
         B is the always-false `and` guard at Halo2Verifier.sol:577."
    );
}
